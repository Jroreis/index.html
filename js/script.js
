document.getElementById('btn-pdf').addEventListener('click', function() {
    const { jsPDF } = window.jspdf;
    const doc = new jsPDF();
    
    // Tema e Cores
    doc.setFillColor(255, 193, 7); // Amber
    doc.rect(0, 0, 210, 20, 'F');
    
    doc.setFont("helvetica", "bold");
    doc.setTextColor(0, 0, 0);
    doc.setFontSize(16);
    doc.text("CALCVOLTPRO - LAUDO TÉCNICO", 10, 14);

    if(config.logo) {
        doc.addImage(config.logo, 'JPEG', 180, 2, 16, 16);
    }
    
    doc.setTextColor(0, 0, 0);
    doc.setFontSize(14);
    doc.text(currentTitle.toUpperCase(), 10, 40);
    doc.line(10, 42, 200, 42);
    
    doc.setFontSize(11);
    doc.setFont("helvetica", "normal");
    
    let y = 55;
    for(let key in currentResult) {
        doc.setFont("helvetica", "bold");
        doc.text(`${key}:`, 10, y);
        doc.setFont("helvetica", "normal");
        doc.text(`${currentResult[key]}`, 80, y);
        y += 10;
        doc.setDrawColor(200);
        doc.line(10, y-3, 200, y-3);
    }

    y += 15;
    doc.setFontSize(10);
    doc.setFont("helvetica", "bold");
    doc.text("FUNDAMENTAÇÃO NORMATIVA:", 10, y);
    doc.setFont("helvetica", "italic");
    doc.text(currentNorm, 10, y+6);
    
    // Assinatura
    doc.setFont("helvetica", "normal");
    doc.setDrawColor(0);
    doc.line(60, 260, 150, 260);
    doc.text(config.nome, 105, 266, {align: "center"});
    doc.setFontSize(9);
    doc.text(config.crea, 105, 271, {align: "center"});
    doc.text(config.empresa, 105, 276, {align: "center"});
    
    doc.save(`Laudo_${currentTitle.replace(/\s+/g, '_')}.pdf`);
});
