// --- EXIBIR RESULTADOS ---
function showResult(title, data, norma) {
    currentTitle = title; currentResult = data; currentNorm = norma;
    let html = "";
    for (let key in data) {
        html += `<div class="res-row"><span class="res-label">${key}:</span><span class="res-val">${data[key]}</span></div>`;
    }
    document.getElementById('resultado-box').innerHTML = html;
    document.getElementById('resultado-container').style.display = 'block';
    
    // Rolar para o resultado suavemente
    document.getElementById('resultado-container').scrollIntoView({behavior: "smooth"});
}

// --- FUNÇÕES DE CÁLCULO ---
function calcCabos() {
    let i = parseFloat(document.getElementById('bt-corrente').value) || 0;
    let l = parseFloat(document.getElementById('bt-dist').value) || 0;
    if(i===0 || l===0) return alert("Preencha os campos corretamente");
    let secTeorica = (2 * 0.01722 * l * i) / (220 * 0.04);
    showResult("Dimensionamento de Cabos BT", {
        "Circuito": "Monofásico 220V", "Corrente": `${i} A`, "Distância": `${l} m`, "Secção Teórica": `${secTeorica.toFixed(2)} mm²`,
        "Cabo Comercial Adotado": Matriz.cabo(secTeorica), "Disjuntor Termomagnético": Matriz.disjuntor(i * 1.25)
    }, "ABNT NBR 5410 - Critério Queda Tensão 4%");
}

function calcEletro() {
    let sec = parseFloat(document.getElementById('bt-sec').value) || 0;
    let qtd = parseInt(document.getElementById('bt-qtd').value) || 1;
    let diam = Math.sqrt((4 * sec) / Math.PI) * 1.5;
    let areaC = (Math.PI * Math.pow(diam, 2) / 4) * qtd;
    let taxa = qtd === 1 ? 0.53 : (qtd === 2 ? 0.31 : 0.40);
    let areaE = areaC / taxa;
    let diamMm = Math.sqrt((4 * areaE) / Math.PI);
    showResult("Taxa de Ocupação", {
        "Condutor Base": `${sec} mm²`, "Qtd de Condutores": `${qtd}`, "Taxa de Ocupação Máx": `${taxa*100}%`,
        "Eletroduto Comercial PVC": Matriz.eletroduto(diamMm)
    }, "ABNT NBR 5410");
}

function calcMotor() {
    let cv = parseFloat(document.getElementById('ind-cv').value) || 0;
    let iN = (cv * 736) / (Math.sqrt(3) * 380 * 0.85 * 0.88);
    let k1 = iN / Math.sqrt(3); let k3 = iN / 3;
    showResult("Painel Estrela-Triângulo", {
        "Motor Trifásico": `${cv} CV (380V)`, "Corrente (In)": `${iN.toFixed(2)} A`, "Disjuntor Motor": Matriz.disjuntor(iN * 1.25),
        "K1 (Rede) / K2 (Triângulo)": Matriz.contator(k1), "K3 (Estrela)": Matriz.contator(k3), "Relé Térmico (Ajuste)": `${k1.toFixed(2)} A`
    }, "Instalações Industriais (Mamede)");
}

function calcFP() {
    let p = parseFloat(document.getElementById('ind-kw').value) || 0;
    let fp1 = parseFloat(document.getElementById('ind-fp1').value) || 0.01;
    let fp2 = parseFloat(document.getElementById('ind-fp2').value) || 0.95;
    let qc = p * (Math.tan(Math.acos(fp1)) - Math.tan(Math.acos(fp2)));
    showResult("Fator de Potência", {
        "Potência Ativa": `${p} kW`, "FP Registado": `${fp1}`, "FP Desejado": `${fp2}`,
        "Banco de Capacitores": `${qc.toFixed(2)} kVAr`
    }, "Instalações Industriais (Mamede)");
}

function calcAT() {
    let icc = parseFloat(document.getElementById('at-icc').value) || 0;
    let xr = parseFloat(document.getElementById('at-xr').value) || 15;
    let k = Math.sqrt(1 + 2 * Math.exp(-2 * Math.PI / xr));
    let iccAssi = icc * k;
    showResult("Esforço Eletrodinâmico (Ruptura)", {
        "Icc Simétrico (RMS)": `${icc} kA`, "Relação X/R": `${xr}`, "Fator de Assimetria": `${k.toFixed(2)}`,
        "Capacidade de Ruptura (Assi)": `${iccAssi.toFixed(2)} kA`, "Pico de Fechamento (Peak)": `${(icc*2.6).toFixed(2)} kA`
    }, "Disjuntores e Chaves - Aplicação em Sistemas de Potência");
}

function calcTermica() {
    let icc = parseFloat(document.getElementById('at-icct').value) || 0;
    let t = parseFloat(document.getElementById('at-tempo').value) || 0.2;
    let secT = (icc * Math.sqrt(t)) / 115;
    showResult("Suportabilidade Térmica a Curto", {
        "Corrente Icc": `${icc} A`, "Tempo de Abertura": `${t} s`, "Secção Mínima I²t": `${secT.toFixed(2)} mm²`,
        "Cabo Comercial Mínimo p/ Curto": Matriz.cabo(secT)
    }, "ABNT NBR 5410 e Cotrim");
}

function calcMalha() {
    let h = parseFloat(document.getElementById('spda-h').value) || 0;
    let p = parseFloat(document.getElementById('spda-p').value) || 0;
    let desc = Math.max(2, Math.ceil(p / 15));
    showResult("SPDA - Estrutural", {
        "Nível Adotado": "Nível III (Comercial Padrão)", "Altura": `${h} m`, "Esfera Rolante": "45 m",
        "Malha Captora": "15x15 m", "Descidas Necessárias": `${desc} (a cada 15m)`
    }, "ABNT NBR 5419");
}

function calcHaste() {
    let rho = parseFloat(document.getElementById('spda-rho').value) || 100;
    let r = (rho / (2 * Math.PI * 2.4)) * Math.log((4 * 2.4) / 0.015);
    showResult("Resistência de Aterramento", {
        "Resistividade": `${rho} Ω.m`, "Haste Cobre": "2.4m x 15mm", "Resistência Prevista": `${r.toFixed(2)} Ω`
    }, "Fórmula de Sunde/Dwight");
}

function calcDemanda() {
    let a = parseFloat(document.getElementById('dist-apt').value) || 0;
    let p = parseFloat(document.getElementById('dist-com').value) || 0;
    let d = (a * 0.40) + p; let kva = d / 0.92;
    showResult("Demanda Predial", {
        "Carga Ativa Total": `${a+p} kW`, "Demanda Calculada": `${d.toFixed(2)} kW`, "Potência Aparente": `${kva.toFixed(2)} kVA`,
        "Transformador Comercial": Matriz.trafo(kva)
    }, "Metodologia Hélio Creder");
}

function calcLux() {
    let c = parseFloat(document.getElementById('lux-c').value) || 0;
    let l = parseFloat(document.getElementById('lux-l').value) || 0;
    let h = parseFloat(document.getElementById('lux-h').value) || 1;
    let k = (c * l) / (h * (c + l));
    showResult("Luminotécnica", {
        "Dimensões": `${c}m x ${l}m`, "Altura Útil": `${h}m`, "Índice de Recinto (K)": `${k.toFixed(2)}`,
        "Observação": "Usar Fator K no catálogo do fabricante da luminária."
    }, "Método dos Lúmens (Projetos Arquitetónicos)");
}

