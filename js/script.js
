// --- MATRIZ COMERCIAL DE ENGENHARIA ---
const Matriz = {
    cabo: (v) => {
        const c = [1.5, 2.5, 4.0, 6.0, 10.0, 16.0, 25.0, 35.0, 50.0, 70.0, 95.0, 120.0, 150.0, 185.0, 240.0, 300.0, 400.0, 500.0];
        for (let b of c) { if (b >= v) return `${b} mm²`; } return "Especial (>500mm²)";
    },
    disjuntor: (v) => {
        const d = [10, 16, 20, 25, 32, 40, 50, 63, 80, 100, 125, 160, 200, 250, 320, 400, 500, 630, 800, 1000];
        for (let dis of d) { if (dis >= v) return `${dis}A`; } return "Caixa Aberta (>1000A)";
    },
    contator: (v) => {
        const c = [9, 12, 18, 25, 32, 40, 50, 65, 80, 95, 115, 150, 185, 225, 265, 330, 400, 500];
        for (let con of c) { if (con >= v) return `${con}A (Cat. AC-3)`; } return "Especial (>500A)";
    },
    eletroduto: (mm) => {
        if (mm <= 16) return "1/2\" (16mm)"; if (mm <= 20) return "3/4\" (20mm)";
        if (mm <= 25) return "1\" (25mm)"; if (mm <= 32) return "1 1/4\" (32mm)";
        if (mm <= 40) return "1 1/2\" (40mm)"; if (mm <= 50) return "2\" (50mm)";
        if (mm <= 75) return "3\" (75mm)"; return "4\" (110mm) ou Calha";
    },
    trafo: (v) => {
        const t = [15, 30, 45, 75, 112.5, 150, 225, 300, 500, 750, 1000, 1500, 2000, 3000];
        for (let tr of t) { if (tr >= v) return `${tr} kVA`; } return "Dedicada (>3MVA)";
    }
};

